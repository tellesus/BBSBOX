use bbsbox_client_identity::{
    local::Session,
    recovery::{Engine, Error},
};
use bbsbox_credentials::{Purpose, Purposes};
use zeroize::Zeroizing;

fn pass() -> Zeroizing<String> {
    Zeroizing::new("local identity fixture passphrase".into())
}
fn purposes() -> Purposes {
    Purposes::new(&[Purpose::Authorship, Purpose::IdentityProof]).unwrap()
}

#[test]
fn reopening_preserves_device_but_recovery_creates_a_fresh_receive_only_identity() {
    let engine = Engine::default();
    let session = Session::create(&engine, pass(), purposes()).unwrap();
    let record = session
        .checkpoint(7, b"private ratchet and outbox state")
        .unwrap();
    let opened = Session::open(&engine, &record, pass()).unwrap();
    assert_eq!(opened.session.person_id(), session.person_id());
    assert_eq!(
        opened.session.device().credential().id(),
        session.device().credential().id()
    );
    assert_ne!(
        opened.session.control_incarnation(),
        session.control_incarnation()
    );
    assert_eq!(opened.revision, 7);
    assert_eq!(opened.state.as_slice(), b"private ratchet and outbox state");
    assert!(!opened.session.requires_rejoin());
    assert_ne!(record, session.checkpoint(7, &opened.state).unwrap());
    let kit = session
        .export_recovery(&engine, pass(), b"receive-side state only")
        .unwrap();
    assert!(matches!(
        engine.import(&record, pass()),
        Err(Error::InvalidKit)
    ));
    assert!(matches!(
        Session::open(&engine, &kit, pass()),
        Err(Error::InvalidKit)
    ));
    let recovered = Session::recover(&engine, &kit, pass(), pass(), purposes()).unwrap();
    assert_eq!(recovered.session.person_id(), session.person_id());
    assert_ne!(
        recovered.session.device().credential().id(),
        session.device().credential().id()
    );
    assert_ne!(
        recovered.session.control_incarnation(),
        session.control_incarnation()
    );
    assert!(recovered.session.requires_rejoin());
    assert_eq!(recovered.state.as_slice(), b"receive-side state only");
    let record = recovered.session.checkpoint(1, &recovered.state).unwrap();
    assert!(
        Session::open(&engine, &record, pass())
            .unwrap()
            .session
            .requires_rejoin()
    );
}

#[test]
fn the_pre_vault_recovery_implementation_fixture_still_opens() {
    // Generated by the committed implementation before the shared-sealing refactor.
    let mut lines = include_str!("data/legacy-recovery.txt").lines();
    let person = lines.next().unwrap();
    let hex = lines.next().unwrap();
    let kit = (0..hex.len())
        .step_by(2)
        .map(|offset| u8::from_str_radix(&hex[offset..offset + 2], 16).unwrap())
        .collect::<Vec<_>>();
    let restored = Engine::default()
        .import(
            &kit,
            Zeroizing::new("legacy recovery fixture passphrase".into()),
        )
        .unwrap();
    assert_eq!(restored.person_id().to_string(), person);
    assert_eq!(restored.client_state(), b"legacy receive state");
}
